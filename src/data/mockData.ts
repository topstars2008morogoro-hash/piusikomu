export const NECTA_GRADING_SCALE = [
  { min: 81, max: 100, grade: 'A', remark_en: 'Excellent', remark_sw: 'Bora Sana', color: 'emerald', points: 1 },
  { min: 61, max: 80, grade: 'B', remark_en: 'Very Good', remark_sw: 'Vizuri Sana', color: 'blue', points: 2 },
  { min: 41, max: 60, grade: 'C', remark_en: 'Good / Average', remark_sw: 'Wastani mzuri', color: 'amber', points: 3 },
  { min: 21, max: 40, grade: 'D', remark_en: 'Pass / Weak', remark_sw: 'Hafifu / Wepesi', color: 'orange', points: 4 },
  { min: 0, max: 20, grade: 'F', remark_en: 'Fail / Poor', remark_sw: 'Dhaifu Sana', color: 'rose', points: 5 },
];

export function calculateNectaGrade(marks: number): { grade: NectaGrade; remark_en: string; remark_sw: string; color: string } {
  const rounded = Math.min(100, Math.max(0, Math.round(marks)));
  if (rounded >= 81) return { grade: 'A', remark_en: 'Excellent', remark_sw: 'Bora Sana', color: 'emerald' };
  if (rounded >= 61) return { grade: 'B', remark_en: 'Very Good', remark_sw: 'Vizuri Sana', color: 'blue' };
  if (rounded >= 41) return { grade: 'C', remark_en: 'Good / Average', remark_sw: 'Wastani', color: 'amber' };
  if (rounded >= 21) return { grade: 'D', remark_en: 'Pass / Weak', remark_sw: 'Hafifu', color: 'orange' };
  return { grade: 'F', remark_en: 'Fail', remark_sw: 'Dhaifu Sana', color: 'rose' };
}

